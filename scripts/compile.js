// Compiles AgentStreak.sol (+ the test-only MockAgentId) with solc-js and
// writes artifacts: artifacts/<Name>.json (abi + bytecode) and a
// frontend/abi.js that the static frontend loads.
const fs = require("fs");
const path = require("path");
const solc = require("solc");

const ROOT = path.join(__dirname, "..");
const ARTIFACTS = path.join(ROOT, "artifacts");

const sources = {
  "AgentStreak.sol": fs.readFileSync(path.join(ROOT, "contracts", "AgentStreak.sol"), "utf8"),
  "MockAgentId.sol": fs.readFileSync(path.join(ROOT, "contracts", "MockAgentId.sol"), "utf8"),
};

const input = {
  language: "Solidity",
  sources: Object.fromEntries(Object.entries(sources).map(([f, c]) => [f, { content: c }])),
  settings: {
    // "paris" avoids the PUSH0 opcode (Shanghai+) for maximum EVM
    // compatibility; the contract needs no post-Paris features.
    evmVersion: "paris",
    optimizer: { enabled: true, runs: 200 },
    outputSelection: { "*": { "*": ["abi", "evm.bytecode", "evm.deployedBytecode"] } },
  },
};

const output = JSON.parse(solc.compile(JSON.stringify(input)));
const errors = (output.errors || []).filter((e) => e.severity === "error");
if (errors.length > 0) {
  for (const e of errors) console.error(e.formattedMessage);
  process.exit(1);
}
for (const w of (output.errors || []).filter((e) => e.severity === "warning")) {
  console.warn("warning:", w.formattedMessage);
}

fs.mkdirSync(ARTIFACTS, { recursive: true });
for (const [file, contracts] of Object.entries(output.contracts)) {
  for (const [name, c] of Object.entries(contracts)) {
    const artifact = {
      contractName: name,
      sourceName: file,
      abi: c.abi,
      bytecode: "0x" + c.evm.bytecode.object,
      deployedBytecode: "0x" + c.evm.deployedBytecode.object,
    };
    fs.writeFileSync(path.join(ARTIFACTS, `${name}.json`), JSON.stringify(artifact, null, 2));
    console.log(`compiled ${name}: bytecode ${c.evm.bytecode.object.length / 2} bytes, deployed ${c.evm.deployedBytecode.object.length / 2} bytes`);
  }
}

// Frontend ABI bundle (address filled in after deployment; see DEPLOY.md).
const streak = JSON.parse(fs.readFileSync(path.join(ARTIFACTS, "AgentStreak.json"), "utf8"));
const abiJs = `// Generated by scripts/compile.js — do not edit by hand.\n// Set AGENT_STREAK_ADDRESS after deploying (see DEPLOY.md).\nwindow.AGENT_STREAK_ADDRESS = ""; // e.g. "0x..."\nwindow.AGENT_STREAK_ABI = ${JSON.stringify(streak.abi, null, 2)};\n`;
fs.writeFileSync(path.join(ROOT, "frontend", "abi.js"), abiJs);
console.log("wrote frontend/abi.js");
